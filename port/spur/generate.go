// Reviewed records the gallery code the stored fragment was reviewed against.
type Reviewed struct {
	// Digest is gallery.Model.SourceDigest of Functions.
	Digest    string   `json:"digest"`
	Functions []string `json:"functions"`
}

// ComputeReviewed returns the Reviewed record for the model as it stands.
func ComputeReviewed(m *gallery.Model) (Reviewed, error) {
	digest, err := m.SourceDigest(ReviewedFuncs...)
	if err != nil {
		return Reviewed{}, err
	}
	return Reviewed{Digest: digest, Functions: slices.Clone(ReviewedFuncs)}, nil
}

// Generate returns the contents of lib/geargen/spurgear.py for the gallery model m
// at version, using fragment as the stored Fusion construction. It fails when the
// gallery has drifted from what the mapping and the fragment were written against.
func Generate(m *gallery.Model, version, fragment string, reviewed Reviewed) (string, error) {
	if err := checkCoverage(m); err != nil {
		return "", err
	}
	if err := checkOps(m); err != nil {
		return "", err
	}
	if err := checkReviewed(m, reviewed); err != nil {
		return "", err
	}
	gen, err := newPieces(m)
	if err != nil {
		return "", err
	}
	out := fragment
	for _, r := range []struct{ marker, text string }{
		{"constants", gen.constants()},
		{"inputs", gen.inputs()},
		{"primary_parameters", gen.primaryParameters()},
		{"derived_parameters", gen.derived},
		{"geometry_helpers", gen.helpers},
	} {
		if out, err = Fill(out, r.marker, r.text); err != nil {
			return "", err
		}
	}
	if strings.Contains(out, "@@") {
		return "", fmt.Errorf("fragment has an unfilled marker")
	}
	header := fmt.Sprintf("# Generated by port/cmd/gearport from decad-gallery models/%s at %s.\n"+
		"# Do not edit: change the gallery model or port/spur, then regenerate.\n", m.Package, version)
	return header + out, nil
}

// checkCoverage requires the mapping and the gallery table to list the same entries
// and the mapped Params fields to match the table's.
func checkCoverage(m *gallery.Model) error {
	inTable := map[string]gallery.Parameter{}
	for _, p := range m.Table {
		inTable[p.Name] = p
	}
	mapped := map[string]struct{}{}
	for _, p := range Params {
		mapped[p.Table] = struct{}{}
		entry, ok := inTable[p.Table]
		if !ok {
			return fmt.Errorf("mapping lists %q, which the gallery parameter table no longer defines", p.Table)
		}
		if p.Input != nil && entry.Field != p.Input.GoField {
			return fmt.Errorf("parameter %q reads Params.%s, mapping expects %s", p.Table, entry.Field, p.Input.GoField)
		}
	}
	for _, p := range m.Table {
		if _, ok := mapped[p.Name]; !ok {
			return fmt.Errorf("gallery parameter %q has no mapping: add it to port/spur/mapping.go", p.Name)
		}
	}
	return nil
}

// checkOps requires the gallery build to perform the decad operations the fragment implements.
func checkOps(m *gallery.Model) error {
	ops, err := m.DecadCalls("Build")
	if err != nil {
		return err
	}
	if !slices.Equal(ops, ExpectedOps) {
		return fmt.Errorf("gallery build performs %v, the fragment implements %v: review port/spur/fragments", ops, ExpectedOps)
	}
	return nil
}

func checkReviewed(m *gallery.Model, rec Reviewed) error {
	if !slices.Equal(rec.Functions, ReviewedFuncs) {
		return fmt.Errorf("reviewed.json lists different functions than ReviewedFuncs: run gearport accept")
	}
	now, err := ComputeReviewed(m)
	if err != nil {
		return err
	}
	if now.Digest != rec.Digest {
		return fmt.Errorf("the gallery code behind the fragment changed (%s): review port/spur/fragments, then run gearport accept",
			strings.Join(ReviewedFuncs, ", "))
	}
	return nil
}

var markerLine = regexp.MustCompile(`(?m)^[ \t]*# @@([a-z_]+)@@\n`)

// Fill replaces the line holding the named marker with text, which must end in a newline.
func Fill(src, marker, text string) (string, error) {
	found := 0
	out := markerLine.ReplaceAllStringFunc(src, func(line string) string {
		if markerLine.FindStringSubmatch(line)[1] != marker {
			return line
		}
		found++
		return text
	})
	if found != 1 {
		return "", fmt.Errorf("fragment has %d %q markers, want 1", found, marker)
	}
	return out, nil
}

// pieces holds the generated text for each marker.
type pieces struct {
	m       *gallery.Model
	derived string
	helpers string
	byTable map[string]Param
}

func newPieces(m *gallery.Model) (*pieces, error) {
	p := &pieces{m: m, byTable: map[string]Param{}}
	for _, mp := range Params {
		p.byTable[mp.Table] = mp
	}
	var err error
	if p.derived, err = p.derivedMethod(); err != nil {
		return nil, err
	}
	python, err := gotopy.Transpile(m, "_", MathStructs, MathFuncs)
	if err != nil {
		return nil, fmt.Errorf("translate involute math: %w", err)
	}
	p.helpers = "# Involute sampling, translated from the gallery model's Go source. Do not edit.\n" +
		python + "\n"
	return p, nil
}

func (p *pieces) constants() string {
	var sb strings.Builder
	for _, mp := range Params {
		if mp.Input != nil {
			fmt.Fprintf(&sb, "%s = '%s'\n", mp.Input.Const, mp.Input.ID)
		}
	}
	for _, mp := range Params {
		if mp.Kind != GalleryOnly {
			fmt.Fprintf(&sb, "%s = '%s'\n", mp.Const, mp.Name)
		}
	}
	return sb.String()
}

// goDefault returns the gallery default of a Params field, zero when it has none.
func (p *pieces) goDefault(field string) float64 {
	for _, in := range p.m.Inputs {
		if in.Name == field {
			return in.Default
		}
	}
	return 0
}

func (p *pieces) inputs() string {
	var sb strings.Builder
	for _, mp := range Params {
		in := mp.Input
		if in == nil {
			continue
		}
		if in.Text {
			fmt.Fprintf(&sb, "        inputs.addStringValueInput(%s, '%s', '%s')\n", in.Const, in.Label, in.TextDefault)
			continue
		}
		fmt.Fprintf(&sb, "        inputs.addValueInput(%s, '%s', '%s', adsk.core.ValueInput.createByReal(%s))\n",
			in.Const, in.Label, in.DialogUnit, p.dialogDefault(in))
	}
	return sb.String()
}

// dialogDefault renders the Python default of a dialog input.
func (p *pieces) dialogDefault(in *Input) string {
	v := p.goDefault(in.GoField)
	switch in.Convert {
	case AsDegrees:
		return fmt.Sprintf("math.radians(%s)", formatNumber(math.Round(v*180/math.Pi*1e9)/1e9))
	case AsLength:
		return fmt.Sprintf("to_cm(%s)", formatNumber(v))
	}
	return formatNumber(v)
}

func formatNumber(v float64) string { return fmt.Sprintf("%g", v) }

func (p *pieces) primaryParameters() string {
	var sb strings.Builder
	for _, mp := range Params {
		if mp.Kind != Primary {
			continue
		}
		fmt.Fprintf(&sb, "        self.addParameter(\n            %s, get_value(inputs, %s, '%s'),\n            '%s', '%s')\n",
			mp.Const, mp.Input.Const, mp.Input.ValueUnit, mp.Unit, mp.Comment)
	}
	return sb.String()
}

// kindOfUnit maps the units constructor a gallery table entry names to an expression kind.
func kindOfUnit(unit string) fusionexpr.Kind {
	switch unit {
	case "Millimeters", "Millimeter":
		return fusionexpr.KindLength
	case "Radians", "Radian":
		return fusionexpr.KindAngle
	}
	return fusionexpr.KindNone
}

func (p *pieces) derivedMethod() (string, error) {
	kinds := map[string]fusionexpr.Kind{}
	entries := map[string]gallery.Parameter{}
	for _, e := range p.m.Table {
		kinds[e.Name] = kindOfUnit(e.Unit)
		entries[e.Name] = e
	}
	var sb strings.Builder
	sb.WriteString("    def registerDerivedParameters(self):\n")
	for _, mp := range Params {
		switch mp.Kind {
		case Fixed:
			field := entries[mp.Table].Field
			fmt.Fprintf(&sb, "        expression = '%s'\n", formatNumber(p.goDefault(field)))
			p.writeAdd(&sb, mp)
		case Derived:
			if err := p.writeDerived(&sb, mp, entries[mp.Table], kinds); err != nil {
				return "", err
			}
		}
	}
	return sb.String(), nil
}

func (p *pieces) writeAdd(sb *strings.Builder, mp Param) {
	fmt.Fprintf(sb, "        self.addParameter(\n            %s, adsk.core.ValueInput.createByString(expression),\n            '%s', '%s')\n",
		mp.Const, mp.Unit, mp.Comment)
}

func (p *pieces) writeDerived(sb *strings.Builder, mp Param, e gallery.Parameter, kinds map[string]fusionexpr.Kind) error {
	res, err := fusionexpr.Translate(e.Expr, kinds)
	if err != nil {
		return fmt.Errorf("parameter %s: %w", mp.Table, err)
	}
	format := res.Format
	args := make([]string, 0, len(res.Names)+1)
	for _, name := range res.Names {
		ref, ok := p.byTable[name]
		if !ok || ref.Kind == GalleryOnly {
			return fmt.Errorf("parameter %s uses %q, which has no Fusion parameter", mp.Table, name)
		}
		args = append(args, fmt.Sprintf("self.parameterName(%s)", ref.Const))
	}
	if mp.HelixFactor {
		format = "(" + format + ") * {}"
		args = append(args, "self.filletHelixFactorExpression()")
	}
	if len(args) == 0 {
		fmt.Fprintf(sb, "        expression = '%s'\n", format)
	} else {
		fmt.Fprintf(sb, "        expression = '%s'.format(\n", format)
		for _, a := range args {
			fmt.Fprintf(sb, "            %s,\n", a)
		}
		sb.WriteString("        )\n")
	}
	p.writeAdd(sb, mp)
	return nil
}
