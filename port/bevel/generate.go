// ComputeReviewed returns the empty record: the pair follows no reviewed code, because the build and its
// validity checks are translated from the gallery.
func ComputeReviewed(m *gallery.Model) (spur.Reviewed, error) { return spur.Reviewed{}, nil }

// Generate returns the contents of lib/geargen/bevelgear.py for the gallery model m at version, using
// fragment as the Fusion wiring. It fails when the gallery has drifted from what the mapping was written
// against.
func Generate(m *gallery.Model, version, fragment string, reviewed spur.Reviewed) (string, error) {
	if err := checkInputs(m); err != nil {
		return "", err
	}
	translated, err := go2py.TranspileSpec(m, FeatureSpec)
	if err != nil {
		return "", fmt.Errorf("translate the bevel pair: %w", err)
	}
	inputs, err := inputsBlock(m)
	if err != nil {
		return "", err
	}
	out := fragment
	for _, r := range []struct{ marker, text string }{
		{"inputs", inputs},
		{"params_class", paramsClass(m)},
		{"params_from_inputs", paramsFromInputs(m)},
		{"translated", "# Translated from the gallery's bevel gear model. Do not edit.\n" + translated + "\n"},
	} {
		if out, err = spur.Fill(out, r.marker, r.text); err != nil {
			return "", err
		}
	}
	if strings.Contains(out, "@@") {
		return "", fmt.Errorf("fragment has an unfilled marker")
	}
	header := fmt.Sprintf("# Generated by port/cmd/gearport from decad-gallery models/%s at %s.\n"+
		"# Do not edit: change the gallery model or port/bevel, then regenerate.\n", m.Package, version)
	return spur.Stamp("bevelgear", header+out), nil
}

// paramsClass renders the Python record of the gallery Params fields. It is a class, because the gallery
// copies a Params and changes the copy.
func paramsClass(m *gallery.Model) string {
	var sb strings.Builder
	params := make([]string, len(m.Inputs))
	for i, in := range m.Inputs {
		params[i] = in.Name + "=None"
	}
	fmt.Fprintf(&sb, "class _Params:\n    def __init__(self, %s):\n", strings.Join(params, ", "))
	for _, in := range m.Inputs {
		fmt.Fprintf(&sb, "        self.%s = %s\n", in.Name, in.Name)
	}
	sb.WriteString("\n    def __eq__(self, other):\n        return vars(self) == vars(other)\n")
	sb.WriteString("\n    def _copy(self):\n        return _Params(**vars(self))\n")
	return sb.String()
}

// paramsFromInputs renders the function that reads the gallery Params, in millimetres and radians, from the
// dialog inputs. A field with no dialog input takes the gallery default.
func paramsFromInputs(m *gallery.Model) string {
	byField := map[string]Input{}
	for _, in := range Inputs {
		byField[in.Field] = in
	}
	var sb strings.Builder
	sb.WriteString("    return _Params(\n")
	for _, g := range m.Inputs {
		in, ok := byField[g.Name]
		if !ok {
			switch g.Name {
			case "Placement":
				fmt.Fprintf(&sb, "        %s=None,\n", g.Name)
			case "Samples":
				fmt.Fprintf(&sb, "        %s=%d,\n", g.Name, int(g.Default))
			default:
				fmt.Fprintf(&sb, "        %s=%s,\n", g.Name, number(g.Default))
			}
			continue
		}
		item := fmt.Sprintf("inputs.itemById(%s)", in.Const)
		switch in.Kind {
		case Number:
			if g.Type == "int" {
				fmt.Fprintf(&sb, "        %s=int(round(%s.value)),\n", g.Name, item)
			} else {
				fmt.Fprintf(&sb, "        %s=%s.value,\n", g.Name, item)
			}
		case Angle:
			if g.Name == "SpiralAngle" {
				// Straight teeth build with a spiral angle of zero, whatever the hidden field holds.
				fmt.Fprintf(&sb, "        %s=%s.value if _is_spiral(inputs) else 0.0,\n", g.Name, item)
			} else {
				fmt.Fprintf(&sb, "        %s=%s.value,\n", g.Name, item)
			}
		case Length:
			fmt.Fprintf(&sb, "        %s=to_mm(%s.value),\n", g.Name, item)
		case Bool:
			fmt.Fprintf(&sb, "        %s=%s.value,\n", g.Name, item)
		case Hand:
			fmt.Fprintf(&sb, "        %s=%s.selectedItem.name.lower(),\n", g.Name, item)
		}
	}
	sb.WriteString("    )\n")
	return sb.String()
}

// checkInputs requires the mapping and the gallery Params to list the same fields.
func checkInputs(m *gallery.Model) error {
	have := map[string]bool{}
	for _, in := range m.Inputs {
		have[in.Name] = true
	}
	mapped := map[string]bool{}
	for _, in := range Inputs {
		if in.Field == "" {
			continue
		}
		mapped[in.Field] = true
		if !have[in.Field] {
			return fmt.Errorf("mapping lists Params.%s, which the gallery no longer defines: update port/bevel", in.Field)
		}
	}
	for _, f := range GalleryOnly {
		mapped[f] = true
		if !have[f] {
			return fmt.Errorf("mapping lists Params.%s, which the gallery no longer defines: update port/bevel", f)
		}
	}
	for _, in := range m.Inputs {
		if !mapped[in.Name] {
			return fmt.Errorf("gallery Params.%s has no mapping: add it to port/bevel/mapping.go", in.Name)
		}
	}
	return nil
}

// inputsBlock renders the dialog inputs, in dialog order, with the gallery defaults.
func inputsBlock(m *gallery.Model) (string, error) {
	byField := map[string]gallery.Input{}
	for _, in := range m.Inputs {
		byField[in.Name] = in
	}
	entries := make([]string, 0, len(Inputs))
	for _, in := range Inputs {
		g := byField[in.Field]
		switch in.Kind {
		case ToothType:
			entries = append(entries, fmt.Sprintf("        toothInput = inputs.addDropDownCommandInput(\n"+
				"            %s, '%s',\n            adsk.core.DropDownStyles.TextListDropDownStyle)\n"+
				"        toothInput.listItems.add(_TOOTH_STRAIGHT, True)\n        toothInput.listItems.add(_TOOTH_SPIRAL, False)\n",
				in.Const, in.Label))
		case Number:
			entries = append(entries, valueInput(in, "''", fmt.Sprintf("createByReal(%s)", number(g.Default))))
		case Angle:
			deg := math.Round(g.Default*180/math.Pi*1e9) / 1e9
			entries = append(entries, valueInput(in, "'deg'", fmt.Sprintf("createByString('%s deg')", number(deg))))
		case Length:
			entries = append(entries, valueInput(in, "'mm'", fmt.Sprintf("createByReal(to_cm(%s))", number(g.Default))))
		case Bool:
			if g.DefaultText != "true" && g.DefaultText != "false" {
				return "", fmt.Errorf("gallery Params.%s default %q is not a bool", in.Field, g.DefaultText)
			}
			py := map[string]string{"true": "True", "false": "False"}[g.DefaultText]
			entries = append(entries, fmt.Sprintf("        inputs.addBoolValueInput(%s, '%s', True, '', %s)\n",
				in.Const, in.Label, py))
		case Hand:
			if g.DefaultText != "right" && g.DefaultText != "left" {
				return "", fmt.Errorf("gallery Params.%s default %q is not right or left", in.Field, g.DefaultText)
			}
			right := map[bool]string{true: "True", false: "False"}
			entries = append(entries, fmt.Sprintf("        handInput = inputs.addDropDownCommandInput(\n"+
				"            %s, '%s',\n            adsk.core.DropDownStyles.TextListDropDownStyle)\n"+
				"        handInput.listItems.add(_HAND_RIGHT, %s)\n        handInput.listItems.add(_HAND_LEFT, %s)\n",
				in.Const, in.Label, right[g.DefaultText == "right"], right[g.DefaultText == "left"]))
		}
	}
	return strings.Join(entries, "\n") + "\n", nil
}

func valueInput(in Input, unit, value string) string {
	return fmt.Sprintf("        inputs.addValueInput(\n            %s, '%s', %s,\n            adsk.core.ValueInput.%s)\n",
		in.Const, in.Label, unit, value)
}

func number(v float64) string { return fmt.Sprintf("%g", v) }
