// ComputeReviewed returns the record of the gallery code the fragment follows.
func ComputeReviewed(m *gallery.Model) (spur.Reviewed, error) {
	digest, err := m.SourceDigest(ReviewedFuncs...)
	if err != nil {
		return spur.Reviewed{}, err
	}
	tr, err := go2py.Translate(m, FeatureSpec)
	if err != nil {
		return spur.Reviewed{}, err
	}
	return spur.Reviewed{Digest: digest, Functions: slices.Clone(ReviewedFuncs), Creations: tr.Creations}, nil
}

// Generate returns the contents of lib/geargen/helicalgear.py for the gallery model m
// at version, using fragment as the Fusion wiring. It fails when the gallery has drifted
// from what the mapping was written against.
func Generate(m *gallery.Model, version, fragment string, reviewed spur.Reviewed) (string, error) {
	def, err := helixDefault(m)
	if err != nil {
		return "", err
	}
	if !slices.Equal(reviewed.Functions, ReviewedFuncs) {
		return "", fmt.Errorf("reviewed.json lists different functions than ReviewedFuncs: run gearport accept")
	}
	now, err := ComputeReviewed(m)
	if err != nil {
		return "", err
	}
	if now.Digest != reviewed.Digest {
		return "", fmt.Errorf("the gallery code behind the fragment changed (%s): review port/helical, "+
			"then run gearport accept", strings.Join(ReviewedFuncs, ", "))
	}
	tr, err := go2py.Translate(m, FeatureSpec)
	if err != nil {
		return "", fmt.Errorf("translate the helical build: %w", err)
	}
	if err := spur.CheckCreations("helicalgear", reviewed, tr.Creations); err != nil {
		return "", err
	}
	translated := tr.Python
	registration, err := Registration(PlaneOffset)
	if err != nil {
		return "", err
	}
	fillet, err := Registration(FilletRadius)
	if err != nil {
		return "", err
	}
	derived := fmt.Sprintf("        self.addParameter(\n            %s,\n"+
		"            adsk.core.ValueInput.createByString(self.helixPlaneOffsetExpression()),\n"+
		"            '%s', '%s')\n", PlaneOffset.Const, PlaneOffset.Unit, PlaneOffset.Comment) +
		fillet + fmt.Sprintf("        self.addParameter(\n            %s, adsk.core.ValueInput.createByString(expression),\n"+
		"            '%s', '%s')\n", FilletRadius.Const, FilletRadius.Unit, FilletRadius.Comment)
	constants := fmt.Sprintf("%s = '%s'\n%s = '%s'\n%s = '%s'\n%s = '%s'\n",
		Input.ParamConst, Input.ParamName, Input.InputConst, Input.InputID,
		PlaneOffset.Const, PlaneOffset.Name, FilletRadius.Const, FilletRadius.Name)
	input := fmt.Sprintf("        inputs.addValueInput(%s, '%s', '%s', adsk.core.ValueInput.createByReal(math.radians(%g)))\n",
		Input.InputConst, Input.Label, Input.DialogUnit, math.Round(def*180/math.Pi*1e9)/1e9)
	out := fragment
	for _, r := range []struct{ marker, text string }{
		{"constants", constants}, {"inputs", input},
		{"derived_parameters", derived}, {"plane_offset", registration},
		{"translated", "# Translated from the gallery's helical model. Do not edit.\n" + translated + "\n"},
	} {
		if out, err = spur.Fill(out, r.marker, r.text); err != nil {
			return "", err
		}
	}
	if strings.Contains(out, "@@") {
		return "", fmt.Errorf("fragment has an unfilled marker")
	}
	header := fmt.Sprintf("# Generated by port/cmd/gearport from decad-gallery models/%s at %s.\n"+
		"# Do not edit: change the gallery model or port/helical, then regenerate.\n", m.Package, version)
	return spur.Stamp("helicalgear", header+out), nil
}

// Registration renders the Python that registers one Variant parameter as a Fusion user
// parameter, with the expression translated from the gallery's.
func Registration(p Parameter) (string, error) {
	res, err := fusionexpr.Translate(p.Expr, kinds)
	if err != nil {
		return "", fmt.Errorf("parameter %s: %w", p.Table, err)
	}
	if err := fusionexpr.CheckUnit(res.Kind, p.Unit); err != nil {
		return "", fmt.Errorf("parameter %s: %w", p.Table, err)
	}
	var sb strings.Builder
	if len(res.Names) == 0 {
		fmt.Fprintf(&sb, "        expression = '%s'\n", res.Format)
	} else {
		fmt.Fprintf(&sb, "        expression = '%s'.format(\n", res.Format)
		for _, name := range res.Names {
			c, ok := Constants[name]
			if !ok {
				return "", fmt.Errorf("parameter %s uses %q, which has no Fusion parameter", p.Table, name)
			}
			fmt.Fprintf(&sb, "            self.parameterName(%s),\n", c)
		}
		sb.WriteString("        )\n")
	}
	return sb.String(), nil
}

// helixDefault returns the gallery default of the helix angle, in radians, and
// requires the model to add no other input of its own.
func helixDefault(m *gallery.Model) (float64, error) {
	if len(m.Inputs) != 1 || m.Inputs[0].Name != Input.GoField || !m.Inputs[0].HasDefault {
		return 0, fmt.Errorf("gallery helical Params must add exactly %s with a default; got %v: update port/helical",
			Input.GoField, m.Inputs)
	}
	return m.Inputs[0].Default, nil
}
