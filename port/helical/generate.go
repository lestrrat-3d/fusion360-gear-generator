package helical

import (
	"fmt"
	"math"
	"slices"
	"strings"

	"github.com/lestrrat-3d/fusion360-gear-generator/port/gallery"
	"github.com/lestrrat-3d/fusion360-gear-generator/port/spur"
)

// ComputeReviewed returns the record of the gallery code the fragment follows.
func ComputeReviewed(m *gallery.Model) (spur.Reviewed, error) {
	digest, err := m.SourceDigest(ReviewedFuncs...)
	if err != nil {
		return spur.Reviewed{}, err
	}
	return spur.Reviewed{Digest: digest, Functions: slices.Clone(ReviewedFuncs)}, nil
}

// Generate returns the contents of lib/geargen/helicalgear.py for the gallery model m
// at version, using fragment as the stored Fusion construction. It fails when the
// gallery has drifted from what the mapping and the fragment were written against.
func Generate(m *gallery.Model, version, fragment string, reviewed spur.Reviewed) (string, error) {
	def, err := helixDefault(m)
	if err != nil {
		return "", err
	}
	ops, err := m.DecadCalls("Build")
	if err != nil {
		return "", err
	}
	if !slices.Equal(ops, ExpectedOps) {
		return "", fmt.Errorf("gallery build performs %v, the fragment implements %v: review port/helical/fragments",
			ops, ExpectedOps)
	}
	if !slices.Equal(reviewed.Functions, ReviewedFuncs) {
		return "", fmt.Errorf("reviewed.json lists different functions than ReviewedFuncs: run gearport accept")
	}
	now, err := ComputeReviewed(m)
	if err != nil {
		return "", err
	}
	if now.Digest != reviewed.Digest {
		return "", fmt.Errorf("the gallery code behind the fragment changed (%s): review port/helical/fragments, "+
			"then run gearport accept", strings.Join(ReviewedFuncs, ", "))
	}

	constants := fmt.Sprintf("%s = '%s'\n%s = '%s'\n", Input.ParamConst, Input.ParamName, Input.InputConst, Input.InputID)
	input := fmt.Sprintf("        inputs.addValueInput(%s, '%s', '%s', adsk.core.ValueInput.createByReal(math.radians(%g)))\n",
		Input.InputConst, Input.Label, Input.DialogUnit, math.Round(def*180/math.Pi*1e9)/1e9)
	out := fragment
	for _, r := range []struct{ marker, text string }{{"constants", constants}, {"inputs", input}} {
		if out, err = spur.Fill(out, r.marker, r.text); err != nil {
			return "", err
		}
	}
	if strings.Contains(out, "@@") {
		return "", fmt.Errorf("fragment has an unfilled marker")
	}
	header := fmt.Sprintf("# Generated by port/cmd/gearport from decad-gallery models/%s at %s.\n"+
		"# Do not edit: change the gallery model or port/helical, then regenerate.\n", m.Package, version)
	return spur.Stamp("helicalgear", header+out), nil
}

// helixDefault returns the gallery default of the helix angle, in radians, and
// requires the model to add no other input of its own.
func helixDefault(m *gallery.Model) (float64, error) {
	if len(m.Inputs) != 1 || m.Inputs[0].Name != Input.GoField || !m.Inputs[0].HasDefault {
		return 0, fmt.Errorf("gallery helical Params must add exactly %s with a default; got %v: update port/helical",
			Input.GoField, m.Inputs)
	}
	return m.Inputs[0].Default, nil
}
