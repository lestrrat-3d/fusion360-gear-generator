package herringbone

import (
	"fmt"
	"slices"
	"strings"

	"github.com/lestrrat-3d/fusion360-gear-generator/port/gallery"
	"github.com/lestrrat-3d/fusion360-gear-generator/port/spur"
)

// ComputeReviewed returns the record of the gallery code the fragment follows.
func ComputeReviewed(m *gallery.Model) (spur.Reviewed, error) {
	digest, err := m.SourceDigest(ReviewedFuncs...)
	if err != nil {
		return spur.Reviewed{}, err
	}
	return spur.Reviewed{Digest: digest, Functions: slices.Clone(ReviewedFuncs)}, nil
}

// Generate returns the contents of lib/geargen/herringbonegear.py for the gallery
// model m at version, using fragment as the stored Fusion construction. It fails when
// the gallery has drifted from what the fragment was written against.
func Generate(m *gallery.Model, version, fragment string, reviewed spur.Reviewed) (string, error) {
	if m.ParamsAlias != ParamsAlias {
		return "", fmt.Errorf("gallery herringbone Params is %q, want an alias of %s: update port/herringbone",
			m.ParamsAlias, ParamsAlias)
	}
	ops, err := m.DecadCalls("Build")
	if err != nil {
		return "", err
	}
	if !slices.Equal(ops, ExpectedOps) {
		return "", fmt.Errorf("gallery build performs %v, the fragment implements %v: review port/herringbone/fragments",
			ops, ExpectedOps)
	}
	if !slices.Equal(reviewed.Functions, ReviewedFuncs) {
		return "", fmt.Errorf("reviewed.json lists different functions than ReviewedFuncs: run gearport accept")
	}
	now, err := ComputeReviewed(m)
	if err != nil {
		return "", err
	}
	if now.Digest != reviewed.Digest {
		return "", fmt.Errorf("the gallery code behind the fragment changed (%s): review port/herringbone/fragments, "+
			"then run gearport accept", strings.Join(ReviewedFuncs, ", "))
	}
	if strings.Contains(fragment, "@@") {
		return "", fmt.Errorf("fragment has an unfilled marker")
	}
	header := fmt.Sprintf("# Generated by port/cmd/gearport from decad-gallery models/%s at %s.\n"+
		"# Do not edit: change the gallery model or port/herringbone, then regenerate.\n", m.Package, version)
	return spur.Stamp("herringbonegear", header+fragment), nil
}
